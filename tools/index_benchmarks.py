"""Generate benchmarks/INDEX.md — a readable map of the evidence directory.

Artifacts are **not** reorganised into subdirectories, deliberately: the
directive and CONTEXT cite them by exact filename ("every claim in run reports
cites its JSON in benchmarks/"), so moving a file silently breaks the audit
trail that makes those claims checkable. An index gives navigability without
touching a single path.

Within each family the newest run is marked CURRENT. Older ones are kept: a
superseded number is often the more interesting one — v20w's PASS-then-FAIL
pair is only meaningful because both artifacts survive.

    py -3 tools/index_benchmarks.py
"""
import json
import os
import re
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BENCH = os.path.join(ROOT, "benchmarks")
STAMP = re.compile(r"_(\d{8})_(\d{6})\.json$")

# What each family is evidence *for*. Anything unlisted still gets indexed.
FAMILIES = {
    "gate": "Gate verdicts. Binding: per-side floor 0.40, aggregate > 0.50.",
    "match": "Head-to-head matches (the only producer of the a_score schema).",
    "benchmark": "Candidate vs heuristic anchor.",
    "promotion_defense_outcomes": "Post-promotion conversion: true captures vs "
                                  "the -0.5 relabel. The PPC sims curve lives here.",
    "promotion_defense_search": "Search-level probe of the same deck.",
    "forced_capture": "Exhaustive AND/OR search for forced king captures "
                      "(walked-past vs clock-cutoff).",
    "movegen_parity": "E1: native movegen vs python-chess.",
    "monster_api_parity": "E1: the Monster action APIs, both engines.",
    "state_machine_parity": "E1: lockstep state machine comparison.",
    "replay_parity": "E1: recorded games replayed move-for-move.",
    "differential": "E1: randomized differential + rare-case coverage.",
    "eval_parity": "E2: heuristic parity (bit-identical).",
    "encoding_parity": "E2: tensor byte-equality, both layouts.",
    "search_agreement": "E3 gate (a): selected-move agreement.",
    "engine_self_match": "E3 gate (b): old engine vs new at equal sims.",
    "native_speedup": "Component speedups, python vs native.",
    "reuse_benefit": "Tree reuse across moves: carry-over and strength.",
    "value_side_bias": "Value-head side bias.",
    "model_diff": "Checkpoint comparisons.",
    "finish_unconverted": "Resuming -0.5 games with the repaired tools.",
}


def family_of(name):
    base = STAMP.sub("", name)
    best = ""
    for key in FAMILIES:
        if base.startswith(key) and len(key) > len(best):
            best = key
    return best or base.split("_")[0]


def headline(path):
    """One line of the most decision-relevant fields, if we recognise them."""
    try:
        with open(path, "r", encoding="utf-8") as fh:
            d = json.load(fh)
    except Exception:
        return ""
    if not isinstance(d, dict):
        return ""
    for keys, fmt in (
        (("verdict",), lambda d: f"verdict={d['verdict']}"),
        (("agreement_rate",), lambda d: f"agreement={d['agreement_rate']}"),
        (("native_score", "deviation_in_se"),
         lambda d: f"score={d['native_score']} ({d['deviation_in_se']} SE)"),
        (("black_win_rate", "true_capture_rate"),
         lambda d: f"true_captures={d['true_capture_rate']} "
                   f"black_rate={d['black_win_rate']}"),
        (("mismatches", "positions_checked"),
         lambda d: f"{d['positions_checked']} positions, {d['mismatches']} mismatches"),
        (("beyond_tolerance", "positions_checked"),
         lambda d: f"{d['positions_checked']} positions, "
                   f"{d['beyond_tolerance']} beyond tolerance"),
        (("games_walked_past_a_win",),
         lambda d: f"walked_past={d['games_walked_past_a_win']}/{d.get('games_probed')}"),
        (("a_score",), lambda d: f"a_score={d['a_score']}"),
        (("replayed_ok", "diverged"),
         lambda d: f"{d['replayed_ok']} ok / {d['diverged']} diverged"),
    ):
        if all(k in d for k in keys):
            try:
                return fmt(d)
            except Exception:
                return ""
    return ""


def main():
    entries = {}
    for name in sorted(os.listdir(BENCH)):
        if not name.endswith(".json"):
            continue
        path = os.path.join(BENCH, name)
        entries.setdefault(family_of(name), []).append(
            (os.path.getmtime(path), name, headline(path)))

    lines = [
        "# benchmarks/ index",
        "",
        f"_Generated by `tools/index_benchmarks.py` on "
        f"{time.strftime('%Y-%m-%d %H:%M')}. Regenerate after any run._",
        "",
        "Files are never moved or renamed: the directive and CONTEXT cite them "
        "by exact filename, and a moved artifact silently breaks a claim's "
        "evidence. Superseded runs are kept on purpose — a number that was "
        "later overturned is often the more interesting one.",
        "",
        f"**{sum(len(v) for v in entries.values())} artifacts across "
        f"{len(entries)} families.**",
        "",
    ]
    for family in sorted(entries):
        runs = sorted(entries[family], reverse=True)
        lines.append(f"## {family}")
        note = FAMILIES.get(family)
        if note:
            lines.append(f"_{note}_")
        lines.append("")
        for i, (_mtime, name, head) in enumerate(runs):
            mark = " **CURRENT**" if i == 0 else ""
            suffix = f" — {head}" if head else ""
            lines.append(f"- `{name}`{mark}{suffix}")
        lines.append("")

    out = os.path.join(BENCH, "INDEX.md")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {out} ({sum(len(v) for v in entries.values())} artifacts, "
          f"{len(entries)} families)")


if __name__ == "__main__":
    main()
